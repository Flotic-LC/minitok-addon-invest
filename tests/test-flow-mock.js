// ---------------------------------------------------------------------------
// Mock network: routes Toss REST calls to an in-memory order book. No real
// network traffic is ever generated by this file.
// ---------------------------------------------------------------------------
function installMockFetch() {
  const state = { orders: [], conditionalOrders: [] };
  const realFetch = globalThis.fetch;
  globalThis.fetch = async (url, init = {}) => {
    const u = new URL(url);
    const method = (init.method || "GET").toUpperCase();
    const rawBody = init.body && typeof init.body === "string" ? init.body : null;
    let body = null;
    if (rawBody) { try { body = JSON.parse(rawBody); } catch { body = null; } } // form-urlencoded token requests are not JSON
    const respond = (status, payload) => new Response(JSON.stringify(payload), { status, headers: { "content-type": "application/json" } });

    if (u.pathname === "/oauth2/token") return respond(200, { access_token: "mock-token", expires_in: 300 });
    if (u.pathname === "/api/v1/orders" && method === "POST") {
      // Real spec: 200 { result: OrderResponse } — orderId + clientOrderId only, NO status
      const order = { orderId: `o-${state.orders.length + 1}`, status: "PENDING", symbol: body.symbol, side: body.side, orderType: body.orderType, quantity: body.quantity, price: body.price, clientOrderId: body.clientOrderId ?? null };
      state.orders.push(order);
      return respond(200, { result: { orderId: order.orderId, clientOrderId: order.clientOrderId } });
    }
    if (u.pathname === "/api/v1/orders" && method === "GET") {
      // Spec: `status` (OPEN|CLOSED) query param is REQUIRED
      if (!["OPEN", "CLOSED"].includes(u.searchParams.get("status"))) return respond(400, { result: null, error: "invalid-request: status required" });
      // Real spec: { result: { orders, nextCursor, hasNext } } — Order items have no clientOrderId
      const items = state.orders.map(({ clientOrderId, ...rest }) => rest);
      return respond(200, { result: { orders: items, nextCursor: null, hasNext: false } });
    }
    if (/^\/api\/v1\/orders\/[^/]+$/.test(u.pathname) && method === "GET") {
      const id = decodeURIComponent(u.pathname.split("/").pop());
      const hit = state.orders.find(o => o.orderId === id);
      return hit ? respond(200, { result: hit }) : respond(404, { result: null, error: "not-found" });
    }
    if (/^\/api\/v1\/orders\/[^/]+\/cancel$/.test(u.pathname) && method === "POST") {
      const id = decodeURIComponent(u.pathname.split("/").slice(-2)[0]);
      const hit = state.orders.find(o => o.orderId === id);
      if (hit) hit.status = "CANCELED";
      return respond(200, { result: { orderId: id, status: "CANCELED" } });
    }
    if (u.pathname === "/api/v1/conditional-orders" && method === "POST") {
      // Real spec: { result: ConditionalOrderCreateResponse } — id + clientOrderId only, NO status
      const cond = { conditionalOrderId: `c-${state.conditionalOrders.length + 1}`, type: body.type, status: "ACTIVE", symbol: body.symbol, quantity: body.quantity, orderType: body.orderType, clientOrderId: body.clientOrderId ?? null };
      state.conditionalOrders.push(cond);
      return respond(200, { result: { conditionalOrderId: cond.conditionalOrderId, clientOrderId: cond.clientOrderId } });
    }
    if (u.pathname === "/api/v1/conditional-orders" && method === "GET") {
      // Spec: `status` (OPEN|CLOSED) query param is REQUIRED
      if (!["OPEN", "CLOSED"].includes(u.searchParams.get("status"))) return respond(400, { result: null, error: "invalid-request: status required" });
      return respond(200, { result: { conditionalOrders: state.conditionalOrders, nextCursor: null, hasNext: false } });
    }
    if (/^\/api\/v1\/conditional-orders\/[^/]+$/.test(u.pathname) && method === "GET") {
      const id = decodeURIComponent(u.pathname.split("/").pop());
      const hit = state.conditionalOrders.find(c => c.conditionalOrderId === id);
      return hit ? respond(200, { result: hit }) : respond(404, { result: null, error: "not-found" });
    }
    if (u.pathname === "/api/v1/prices" && method === "GET") {
      // Spec: `symbols` (comma-separated) query param is REQUIRED
      if (!u.searchParams.get("symbols")) return respond(400, { result: null, error: "invalid-request: symbols required" });
      return respond(200, { result: u.searchParams.get("symbols").split(",").map(s => ({ symbol: s, price: "70000" })) });
    }
    if (u.pathname === "/api/v1/orderbook" && method === "GET") {
      if (!u.searchParams.get("symbol")) return respond(400, { result: null, error: "invalid-request: symbol required" });
      return respond(200, { result: { symbol: u.searchParams.get("symbol"), asks: [], bids: [] } });
    }
    if (u.pathname === "/api/v1/price-limits" && method === "GET") {
      if (!u.searchParams.get("symbol")) return respond(400, { result: null, error: "invalid-request: symbol required" });
      return respond(200, { result: { timestamp: new Date().toISOString(), upperLimitPrice: "91000", lowerLimitPrice: "49000", currency: "KRW" } });
    }
    if (u.pathname === "/api/v1/accounts") return respond(200, { result: [{ accountSeq: "1" }] });
    return respond(404, { result: null, error: `unmocked: ${method} ${u.pathname}` });
  };
  return { state, restore: () => { globalThis.fetch = realFetch; } };
}

const environment = { commands: {}, tools: [], package: {}, capabilities: { local: true }, external_connectivity: true };
function gateOptions(ledger) {
  return {
    capabilities: ["read", "inspect", "external_call", "credential_use"],
    mode: "authorized_external",
    production_adapter_opt_in: true,
    audit_persisted: true,
    integrity_preflight: true,
    environment_observation: environment,
    operation_ledger: ledger,
  };
}

function setupRegistry(limits = {}) {
  resetTokenCache();
  return createAdapterRegistry([createTossInvestAdapter({ clientId: "id", clientSecret: "secret" }, limits)]);
}

// ---------------------------------------------------------------------------

test("full create_order flow completes through minitok external contract", async () => {
  const mock = installMockFetch();
  try {
    const registry = setupRegistry();
    const ledger = new Map();
    const result = await executeAdapter(registry, "api", {
      operation: "create_order",
      target: { accountSeq: "1" },
      symbol: "kr:005930",
      side: "BUY",
      orderType: "LIMIT",
      quantity: 1,
      price: 1000,
    }, gateOptions(ledger));

    assert.equal(result.success, true, JSON.stringify(result));
    assert.equal(result.completed, true, JSON.stringify(result));
    assert.equal(result.status, "completed");
    assert.equal(result.verification.external_state.valid, true);
    assert.equal(result.verification.external_state.executed, true);
    assert.ok(result.operation_audit?.idempotency_key, "idempotency key recorded");
    assert.equal(mock.state.orders.length, 1);
    assert.ok(mock.state.orders[0].clientOrderId, "clientOrderId sent to Toss");
  } finally { mock.restore(); }
});

test("conditional order create flow completes with read-after-write verification", async () => {
  const mock = installMockFetch();
  try {
    const registry = setupRegistry();
    const ledger = new Map();
    const result = await executeAdapter(registry, "api", {
      operation: "create_conditional_order",
      target: { accountSeq: "1" },
      symbol: "kr:005930",
      type: "SINGLE",
      quantity: 1,
      orderType: "LIMIT",
      expireDate: "2026-12-31",
      first: { orderSide: "BUY", triggerPrice: 60000, orderPrice: 60100 },
    }, gateOptions(ledger));

    assert.equal(result.completed, true, JSON.stringify(result));
    assert.equal(result.verification.external_state.valid, true);
    assert.equal(mock.state.conditionalOrders.length, 1);
    assert.ok(mock.state.conditionalOrders[0].clientOrderId, "idempotency key as clientOrderId");
  } finally { mock.restore(); }
});

test("conditional order value limit blocks before any network call", async () => {
  const mock = installMockFetch();
  try {
    const registry = setupRegistry({ maxOrderValueKrw: 500000 });
    const result = await executeAdapter(registry, "api", {
      operation: "create_conditional_order",
      target: { accountSeq: "1" },
      symbol: "kr:005930",
      type: "SINGLE",
      quantity: 10,
      orderType: "LIMIT",
      expireDate: "2026-12-31",
      first: { orderSide: "BUY", triggerPrice: 100000, orderPrice: 100000 },
    }, gateOptions(new Map()));
    assert.equal(result.success, false);
    assert.equal(result.code, "ORDER_VALUE_EXCEEDED");
    assert.equal(mock.state.conditionalOrders.length, 0, "no order reached the broker");
  } finally { mock.restore(); }
});

test("cancel_order flow completes", async () => {
  const mock = installMockFetch();
  try {
    const registry = setupRegistry();
    const ledger = new Map();
    mock.state.orders.push({ orderId: "o-9", clientOrderId: "seed", status: "OPEN" });
    const result = await executeAdapter(registry, "api", {
      operation: "cancel_order",
      target: { accountSeq: "1" },
      orderId: "o-9",
    }, gateOptions(ledger));
    assert.equal(result.completed, true, JSON.stringify(result));
    assert.equal(mock.state.orders[0].status, "CANCELED");
  } finally { mock.restore(); }
});

test("identical create_order replay is rejected as duplicate by the ledger", async () => {
  const mock = installMockFetch();
  try {
    const registry = setupRegistry();
    const ledger = new Map();
    const input = {
      operation: "create_order",
      target: { accountSeq: "1" },
      symbol: "kr:005930", side: "BUY", orderType: "LIMIT", quantity: 1, price: 1000,
    };
    const first = await executeAdapter(registry, "api", input, gateOptions(ledger));
    assert.equal(first.completed, true);
    const second = await executeAdapter(registry, "api", input, gateOptions(ledger));
    assert.equal(second.completed, false);
    assert.equal(second.code, "DUPLICATE_EXTERNAL_OPERATION");
    assert.equal(mock.state.orders.length, 1, "broker saw exactly one order");
  } finally { mock.restore(); }
});
